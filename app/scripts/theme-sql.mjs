// Prints the one-time database update that gives a student Emma's look.
// Usage: node scripts/theme-sql.mjs > theme-data/apply-emma-theme.sql
// It changes data only (her empty "Starter" theme row). Nothing in this script touches the database.
import { readFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("../theme-data/emma.theme.json", import.meta.url), "utf8"));
const j = (v) => `$j$${JSON.stringify(v)}$j$::jsonb`;

console.log(`-- Gives Emma her look. Run once in the Supabase SQL editor, AFTER her account exists.
-- Replace EMMAS_USERNAME below with the username she chose. Generated by app/scripts/theme-sql.mjs.
update public.themes set
  name = $j$${t.name}$j$,
  theming_depth = '${t.theming_depth}',
  palette = ${j(t.palette)},
  fonts = ${j(t.fonts)},
  shapes = ${j(t.shapes)},
  page_names = ${j(t.page_names)},
  currency = ${j(t.currency)},
  wording = ${j(t.wording)},
  color_system = ${j(t.color_system)}
where student_id = (select id from public.profiles where username = 'EMMAS_USERNAME' and role = 'student')
  and name = 'Starter'
returning name;
-- Worked: one row comes back, named "Emma (kawaii)".
-- "Success. No rows returned" means nothing changed: the username is wrong, or her theme was already changed.`);
